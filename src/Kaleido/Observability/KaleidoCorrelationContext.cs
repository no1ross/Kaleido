namespace Kaleido.Observability;

/// <summary>
/// Correlation for the current request. <see cref="RequestId"/>, <see cref="ProcessId"/> and the
/// origin (<see cref="Origin"/>, <see cref="OriginTool"/>) are end-to-end: forwarded unchanged on every hop. <see cref="CallingProcessorName"/> and
/// <see cref="CallingStepName"/> are per-hop: they describe the processor step that called
/// this service and are never forwarded. A service's own instance id is never on the wire.
/// </summary>
public sealed record KaleidoCorrelationContext
{
    /// <summary>
    /// The unique identifier of the originating request.
    /// Always non-empty — generated by the transport layer if not supplied by the caller.
    /// </summary>
    public string RequestId
    {
        get;
        init;
    } = string.Empty;

    /// <summary>The process instance this request belongs to (end-to-end).</summary>
    public Guid? ProcessId
    {
        get;
        init;
    }

    /// <summary>
    /// The processor whose step made this call (per-hop, inbound). <see langword="null"/> when the
    /// call was not made from inside a processor step — e.g. routed or registry calls.
    /// </summary>
    public string? CallingProcessorName
    {
        get;
        init;
    }

    /// <summary>The step in <see cref="CallingProcessorName"/> that made this call (per-hop, inbound).</summary>
    public string? CallingStepName
    {
        get;
        init;
    }

    /// <summary>
    /// The front door the request came through (e.g. <c>mcp</c>), end-to-end: set by the front door,
    /// forwarded on every hop, recorded on events and spans. Informational - any caller can send it -
    /// so never an authorization input; <see cref="CallerActor"/> is the trusted counterpart.
    /// <see langword="null"/> for a request that did not come through a front door.
    /// </summary>
    public string? Origin
    {
        get;
        init;
    }

    /// <summary>The front door's name for what started the request (the MCP tool), end-to-end; informational like <see cref="Origin"/>.</summary>
    public string? OriginTool
    {
        get;
        init;
    }

    /// <summary>
    /// The application acting for the caller on this hop (a calling service or the front door), from
    /// the authenticated principal's actor claim (<c>act</c>, else <c>azp</c>, else <c>appid</c>) - never
    /// from headers. Per-hop: each service reads its own caller's token. <see langword="null"/> when the
    /// principal names none.
    /// </summary>
    public string? CallerActor
    {
        get;
        init;
    }

    /// <summary>
    /// The step this service is currently executing. Set by the runtime for a step
    /// handler's scope; outbound calls made from that scope stamp it, with this
    /// service's name, as the calling processor and step. <see langword="null"/> outside a step.
    /// </summary>
    public string? ExecutingStepName
    {
        get;
        init;
    }

    /// <summary>
    /// Name of the authenticated caller, populated by the transport from the
    /// request principal — <b>never</b> from caller-supplied headers.
    /// <see langword="null"/> for anonymous requests.
    /// </summary>
    public string? CallerName
    {
        get;
        init;
    }

    /// <summary>
    /// Stable subject id of the authenticated caller (the <c>sub</c> claim, else
    /// <c>ClaimTypes.NameIdentifier</c>), populated by the transport from the request principal -
    /// <b>never</b> from caller-supplied headers. <see langword="null"/> for anonymous requests or a
    /// principal without one.
    /// </summary>
    public string? CallerId
    {
        get;
        init;
    }

    /// <summary>
    /// The caller as Kaleido tags it on events and state: <see cref="CallerName"/> and
    /// <see cref="CallerId"/>. <see langword="null"/> when neither is known (anonymous).
    /// </summary>
    public KaleidoCaller? Caller =>
        CallerName is null && CallerId is null
            ? null
            : new KaleidoCaller { Name = CallerName, Id = CallerId };
    /// <summary>
    /// Whether the caller is authenticated, set by the transport from the request principal
    /// (<c>Identity.IsAuthenticated</c>) - <b>never</b> from caller-supplied headers. Authorization
    /// reads this, not the presence of a name: a principal without a name (a subject-only or a
    /// client-credentials token) is authenticated all the same (#515).
    /// </summary>
    public bool CallerIsAuthenticated
    {
        get;
        init;
    }

    /// <summary>
    /// Roles of the authenticated caller, populated by the transport for any authenticated caller,
    /// named or not (see <see cref="CallerIsAuthenticated"/>). Empty for anonymous requests.
    /// </summary>
    public IReadOnlyCollection<string> CallerRoles
    {
        get;
        init;
    } = [];

    /// <summary>
    /// Returns <see langword="true"/> when the correlation context has no meaningful correlation fields set —
    /// indicating no correlation context has been established for the current request.
    /// </summary>
    public bool IsEmpty =>
        string.IsNullOrWhiteSpace(RequestId)
        && ProcessId is null
        && string.IsNullOrWhiteSpace(CallingProcessorName)
        && string.IsNullOrWhiteSpace(CallingStepName);
}
